CREATE TABLE EMPRESA(
    ID TEXT PRIMARY KEY NOT NULL,
    CIF VARCHAR(9) NOT NULL,
    Persona VARCHAR(255) NOT NULL,
    Correo VARCHAR(255) NOT NULL,
    Telefono VARCHAR(15) NOT NULL,
    Razon_Social TEXT NOT NULL,
    Domicilio TEXT NOT NULL,
    Contraseña VARCHAR(255) NOT NULL,
    Verificada BOOLEAN NOT NULL DEFAULT FALSE,
    Restringida BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TYPE estado_festival AS ENUM ('Activo', 'Cancelado');

CREATE TABLE FESTIVAL(
    ID VARCHAR(255) PRIMARY KEY NOT NULL,
    Nombre VARCHAR(255) NOT NULL,
    Estado estado_festival NOT NULL,
    CHECK (Estado IN ('Activo', 'Cancelado')),
    Ubicacion TEXT NOT NULL,
    Aforo INT NOT NULL,
    Descripcion TEXT NOT NULL,
    F_Inicio DATE NOT NULL,
    F_Fin DATE NOT NULL,
    Imagen TEXT,
    Empresa TEXT,
    FOREIGN KEY (Empresa) REFERENCES EMPRESA(ID)
        ON DELETE SET NULL
        ON UPDATE CASCADE
);

CREATE TABLE ARTISTA(
    ID VARCHAR(255) PRIMARY KEY NOT NULL,
    Nombre VARCHAR(255) NOT NULL,
    Imagen TEXT
);

CREATE TABLE ACTUAR_FESTIVAL(
    Festival VARCHAR(255) NOT NULL,
    Artista VARCHAR(255) NOT NULL,
    PRIMARY KEY (Festival, Artista),
    FOREIGN KEY (Festival) REFERENCES FESTIVAL(ID)
        ON DELETE CASCADE
        ON UPDATE CASCADE,
    FOREIGN KEY (Artista) REFERENCES ARTISTA(ID)
        ON DELETE CASCADE
        ON UPDATE CASCADE
);

CREATE TABLE TIPO_ABONO(
    Nombre VARCHAR(255) NOT NULL,
    Precio DECIMAL(10, 2) NOT NULL,
    Stock INT NOT NULL,
    Festival VARCHAR(255) NOT NULL,
    PRIMARY KEY (Nombre, Festival),
    FOREIGN KEY (Festival) REFERENCES FESTIVAL(ID)
        ON DELETE CASCADE
        ON UPDATE CASCADE
);

CREATE TABLE CLIENTE(
    ID VARCHAR(255) PRIMARY KEY NOT NULL,
    Correo VARCHAR(255) NOT NULL,
    Nombre VARCHAR(255) NOT NULL,
    Apellidos VARCHAR(255) NOT NULL,
    DNI VARCHAR(9) NOT NULL,
    Fecha_Nacimiento DATE NOT NULL,
    Telefono VARCHAR(15) NOT NULL,
    Contraseña VARCHAR(255) NOT NULL
);

CREATE TABLE ABONO_CLIENTE(
    ID VARCHAR(255) NOT NULL,
    Saldo DECIMAL(10, 2) NOT NULL,
    Timestamp TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    Tipo_Abono VARCHAR(255) NOT NULL,
    Cliente VARCHAR(255) NOT NULL,
    Festival VARCHAR(255) NOT NULL,
    Estado BOOLEAN NOT NULL DEFAULT TRUE,
    PRIMARY KEY (ID, Cliente, Festival, Tipo_Abono),
    FOREIGN KEY (Tipo_Abono, Festival) REFERENCES TIPO_ABONO(Nombre, Festival)
        ON DELETE CASCADE
        ON UPDATE CASCADE,
    FOREIGN KEY (Cliente) REFERENCES CLIENTE(ID)
        ON DELETE SET NULL
        ON UPDATE CASCADE,
    FOREIGN KEY (Festival) REFERENCES FESTIVAL(ID)
        ON DELETE CASCADE
        ON UPDATE CASCADE
);

CREATE TYPE TIPO_TRANSACCION AS ENUM ('Compra', 'Recarga');

CREATE TABLE TRANSACCION(
    ID VARCHAR(255) PRIMARY KEY NOT NULL,
    Cantidad DECIMAL(10, 2) NOT NULL,
    Moneda VARCHAR(3) NOT NULL,
    Propietario VARCHAR(255) NOT NULL,
    Timestamp TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE REALIZAR_TRANSACCION(
    Abono VARCHAR(255) NOT NULL,
    Cliente VARCHAR(255) NOT NULL,
    Festival VARCHAR(255) NOT NULL,
    Tipo_Abono VARCHAR(255) NOT NULL,
    Transaccion VARCHAR(255) NOT NULL,
    Tipo_Transaccion TIPO_TRANSACCION NOT NULL,

    PRIMARY KEY (Abono, Cliente, Festival, Tipo_Abono, Transaccion),
    FOREIGN KEY (Abono, Cliente, Festival, Tipo_Abono) REFERENCES ABONO_CLIENTE(ID, Cliente, Festival, Tipo_Abono)
        ON DELETE CASCADE
        ON UPDATE CASCADE,
    FOREIGN KEY (Transaccion) REFERENCES TRANSACCION(ID)
        ON DELETE CASCADE
        ON UPDATE CASCADE
);

